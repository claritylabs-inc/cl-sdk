import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCES = {
  lob: "https://modelviewers.pilotfishtechnology.com/modelviewers/ACORD-PCS/model/LOBCd.html",
  coverage: "https://modelviewers.pilotfishtechnology.com/modelviewers/ACORD-PCS/model/CoverageCd.html",
};

const OUTPUT_URL = new URL("../src/schemas/acord-taxonomy.generated.ts", import.meta.url);

function decodeHtml(value) {
  return value
    .replace(/<[^>]*>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, "\"")
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .replace(/&#(\d+);/g, (_match, codePoint) => String.fromCodePoint(Number(codePoint)))
    .replace(/\s+/g, " ")
    .trim();
}

function parseCells(rowHtml) {
  return Array.from(
    rowHtml.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gi),
    (match) => decodeHtml(match[1]),
  );
}

function parseCodeTable(html) {
  const headerRow = html.match(
    /<tr class="TypeCodeHeaderRow"[^>]*>([\s\S]*?)<\/tr>/i,
  );
  if (!headerRow) throw new Error("Code table header row was not found");
  const headers = parseCells(headerRow[1]);
  const rows = Array.from(
    html.matchAll(
      /<tr class="TypeCodeDetailRow"[^>]*>([\s\S]*?)<\/tr>/gi,
    ),
    (match) => parseCells(match[1]),
  );
  if (rows.some((row) => row.length !== headers.length)) {
    throw new Error("Code table contains a row with an unexpected column count");
  }
  return { headers, rows };
}

function unique(values) {
  return Array.from(new Set(values));
}

function checksum(entries) {
  return createHash("sha256").update(JSON.stringify(entries)).digest("hex");
}

function renderConst(name, value) {
  return `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

function normalizedEntries(table) {
  const codeIndex = table.headers.indexOf("Value");
  const descriptionIndex = table.headers.indexOf("Description");
  if (codeIndex < 0 || descriptionIndex < 0) {
    throw new Error(
      `Expected Value and Description columns, received: ${table.headers.join(", ")}`,
    );
  }
  return table.rows.map((row) => ({
    code: row[codeIndex],
    description: row[descriptionIndex],
  }));
}

function renderTaxonomy(lobTable, coverageTable) {
  const lobEntries = normalizedEntries(lobTable);
  const coverageEntries = normalizedEntries(coverageTable);
  const lobCodes = lobEntries.map(({ code }) => code);
  const lobLabels = Object.fromEntries(
    lobEntries.map(({ code, description }) => [code, description]),
  );
  const coverageCodes = unique(coverageEntries.map(({ code }) => code));
  const coverageDescriptions = Object.fromEntries(
    coverageCodes.map((code) => [
      code,
      unique(
        coverageEntries
          .filter((entry) => entry.code === code)
          .map(({ description }) => description),
      ),
    ]),
  );

  const metadata = {
    sources: SOURCES,
    lob: {
      rowCount: lobEntries.length,
      uniqueCodeCount: lobCodes.length,
      headers: lobTable.headers,
      sha256: checksum(lobTable.rows),
    },
    coverage: {
      rowCount: coverageEntries.length,
      uniqueCodeCount: coverageCodes.length,
      headers: coverageTable.headers,
      sha256: checksum(coverageTable.rows),
    },
  };

  return [
    "// Generated by scripts/generate-acord-taxonomy.mjs. Do not edit by hand.",
    "// The source rows intentionally retain duplicates and conflicting descriptions.",
    "",
    renderConst("ACORD_TAXONOMY_METADATA", metadata),
    renderConst("ACORD_LOB_SOURCE_HEADERS", lobTable.headers),
    renderConst("ACORD_LOB_SOURCE_ROWS", lobTable.rows),
    "export const ACORD_LOB_ENTRIES = ACORD_LOB_SOURCE_ROWS.map(([code, description]) => ({ code, description }));\n",
    renderConst("ACORD_LOB_CODES", lobCodes),
    renderConst("ACORD_LOB_LABELS", lobLabels),
    renderConst("ACORD_COVERAGE_SOURCE_HEADERS", coverageTable.headers),
    renderConst("ACORD_COVERAGE_SOURCE_ROWS", coverageTable.rows),
    "export const ACORD_COVERAGE_ENTRIES = ACORD_COVERAGE_SOURCE_ROWS.map(([code, description]) => ({ code, description }));\n",
    renderConst("ACORD_COVERAGE_CODES", coverageCodes),
    renderConst("ACORD_COVERAGE_DESCRIPTIONS", coverageDescriptions),
  ].join("\n");
}

async function fetchSource(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return await response.text();
}

async function main() {
  const [lobHtml, coverageHtml] = await Promise.all([
    fetchSource(SOURCES.lob),
    fetchSource(SOURCES.coverage),
  ]);
  const lobTable = parseCodeTable(lobHtml);
  const coverageTable = parseCodeTable(coverageHtml);
  const lobEntries = normalizedEntries(lobTable);
  const coverageEntries = normalizedEntries(coverageTable);

  if (lobEntries.length !== 107 || new Set(lobEntries.map(({ code }) => code)).size !== 107) {
    throw new Error(`Expected 107 unique LOB rows, received ${lobEntries.length}`);
  }
  if (coverageEntries.length < 2_000) {
    throw new Error(`Coverage table is unexpectedly small: ${coverageEntries.length} rows`);
  }

  const generated = renderTaxonomy(lobTable, coverageTable);
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT_URL, "utf8");
    if (current !== generated) {
      throw new Error(
        `${fileURLToPath(OUTPUT_URL)} is stale. Run npm run generate:acord-taxonomy.`,
      );
    }
    return;
  }
  await writeFile(OUTPUT_URL, generated);
}

await main();
